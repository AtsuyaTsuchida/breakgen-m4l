#!/usr/bin/env python3
"""Embed model.json (and model2.json if present) into breakgen.js between the MODEL markers."""
import json, os, re
def compact(m):
    r = lambda v: [r(x) for x in v] if isinstance(v, list) else round(v, 5)
    return json.dumps({k: r(v) for k, v in m.items()}, separators=(",", ":"))
src = open("breakgen.js").read()
body = "var CLASSIFIER = %s;\n" % compact(json.load(open("model.json")))
body += "var CLASSIFIER2 = %s;\n" % (compact(json.load(open("model2.json"))) if os.path.exists("model2.json") else "null")
new = re.sub(r"// MODEL-BEGIN.*?// MODEL-END", "// MODEL-BEGIN (generated by test/inject_model.py)\n" + body + "// MODEL-END", src, flags=re.S)
if new == src and "// MODEL-BEGIN" not in src:
    raise SystemExit("markers missing")
open("breakgen.js", "w").write(new)
print("injected", len(body), "bytes")
